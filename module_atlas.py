def classify_role(module_name, filepath=None):
    """Classify a module's functional role.

    Reads the module's declared Role: tag. Signature is unchanged for a
    name-only caller (provenance_scanner.py, dep_trace.py) -- pass
    filepath when you already have it and the lookup skips resolution.

    The old filename heuristic is gone: an unrecognized or missing tag
    now returns UNDETERMINED and gets reported, rather than being guessed
    into a role that reads exactly like a declared one.
    """
    role, _domain, _source = classify_module(module_name, filepath)
    return role


def classify_domain(module_name, filepath=None):
    """Read a module's declared Domain: tag. UNDETERMINED if absent."""
    _role, domain, _source = classify_module(module_name, filepath)
    return domain


