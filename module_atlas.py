def iter_module_files(project_dir):
    """Yield (module_name, filepath) for every module under SCAN_PATHS.

    Returns them merged across all scan paths, plus a list of collisions:
    two directories holding the same module name. The orrery scans one
    flat directory and can never collide; the gallery scans five, and a
    silent shadow there would mean the atlas described one file while the
    imports resolved to another.
    """
    found = {}
    collisions = []
    for scan in SCAN_PATHS:
        directory = os.path.join(project_dir, scan)
        if not os.path.isdir(directory):
            print(f"  WARNING: SCAN_PATHS entry not found: {scan}")
            continue
        for name in sorted(os.listdir(directory)):
            if not name.endswith('.py') or name == '__init__.py':
                continue
            full = os.path.join(directory, name)
            if not os.path.isfile(full):
                continue
            mod = name[:-3]
            if mod in found:
                collisions.append((mod, found[mod], full))
                continue
            found[mod] = full
    return found, collisions


def build_dependency_graph(project_dir):
    """Build bidirectional dependency graph for all local modules.

    Module discovery runs through iter_module_files(), so a repo whose
    modules live in package directories (the gallery) is walked the same
    way as a flat one (the orrery).
    """
    paths, collisions = iter_module_files(project_dir)
    local_modules = set(paths)

    for mod, first, second in collisions:
        print(f"  COLLISION: '{mod}' found in two scan paths -- "
              f"{first} and {second}; using the first")

    deps = {}       # module -> set of modules it imports
    consumers = {}  # module -> set of modules that import it

    for mod, fpath in paths.items():
        imported = get_local_imports(fpath, local_modules)
        deps[mod] = imported
        for imp in imported:
            consumers.setdefault(imp, set()).add(mod)

    return deps, consumers, local_modules


# ============================================================
# SCAN -- shared by both generators, run exactly once per invocation
# ============================================================

def scan_modules(project_dir):
    """Scan every .py file in project_dir once and return the list of
    per-module info dicts that both generate_atlas() and generate_index()
    read from. This is the single source of truth both outputs share --
    running this once and handing the same result to both writers is what
    actually prevents the two files from diverging, not just a naming
    convention."""
    print(f"Scanning {project_dir}...")
    set_tag_source_dir(project_dir)
    paths, _collisions = iter_module_files(project_dir)
    _MODULE_PATHS.clear()
    _MODULE_PATHS.update(paths)

    deps, consumers, local_modules = build_dependency_graph(project_dir)

    modules = []
    for mod in sorted(local_modules):
        fpath = paths.get(mod)
        if not fpath or not os.path.exists(fpath):
            continue

        role, domain, source = classify_module(mod, fpath)
        info = {
            'name': mod,
            'path': os.path.relpath(fpath, project_dir).replace(os.sep, '/'),
            'role': role,
            'domain': domain,
            'role_source': source,
            'docstring': get_module_docstring(fpath),
            'functions': get_public_functions(fpath),
            'lines': count_lines(fpath),
            'deps': sorted(deps.get(mod, set())),
            'consumers': sorted(consumers.get(mod, set())),
        }
        modules.append(info)

    return modules


