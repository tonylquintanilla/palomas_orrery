def main():
    project_dir = '.'
    atlas_path = 'MODULE_ATLAS.md'
    index_path = 'MODULE_INDEX.md'
    do_atlas = True
    do_index = True

    args = sys.argv[1:]
    i = 0
    while i < len(args):
        if args[i] == '--output' and i + 1 < len(args):
            atlas_path = args[i + 1]
            i += 2
        elif args[i] == '--index-output' and i + 1 < len(args):
            index_path = args[i + 1]
            i += 2
        elif args[i] == '--atlas-only':
            do_index = False
            i += 1
        elif args[i] == '--index-only':
            do_atlas = False
            i += 1
        elif not args[i].startswith('-'):
            project_dir = args[i]
            i += 1
        else:
            i += 1

    if not os.path.isdir(project_dir):
        print(f"ERROR: '{project_dir}' is not a directory")
        sys.exit(1)

    modules = scan_modules(project_dir)

    # ROLE_MAP is a mirror of the tags now, so refresh it from this scan
    # before writing the reports. Hand-editing it is what Phase 3 retired.
    regenerate_role_map(modules)

    if do_atlas:
        generate_atlas(modules, atlas_path)
    if do_index:
        generate_index(modules, index_path)


if __name__ == '__main__':
    main()
