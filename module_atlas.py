# TAG PARSER -- the source of truth as of L-163 Phase 3
# ============================================================
# Every module carries its own classification in its docstring:
#
#     Role: <one of ROLE_ORDER>
#     Domain: <one of the repo's domain vocabulary>
#
# Written by add_docstrings.py (L-163 Phase 2). This section reads them.
# A module that does not declare a valid Role is 'undetermined' -- never
# guessed from its filename. The old _shells suffix heuristic is gone on
# purpose: an inferred role that looks identical to a declared one is a
# claim about provenance that isn't true.

TAG_RE = re.compile(r'^[ \t]*(Role|Domain):[ \t]*(\S+)[ \t]*$', re.MULTILINE)

# Filled in by scan_modules(). Lets classify_role() answer a name-only
# question -- which is how provenance_scanner.py and dep_trace.py ask it --
# without either of them needing to know where the file lives.
_MODULE_PATHS = {}

# Fallback directory for a name-only lookup made before any scan has run.
_TAG_SOURCE_DIR = os.path.dirname(os.path.abspath(__file__))


def set_tag_source_dir(project_dir):
    """Point name-only lookups at a specific directory.

    Only needed by a consumer that runs against a tree other than the one
    this file sits in. scan_modules() calls it automatically.
    """
    global _TAG_SOURCE_DIR
    _TAG_SOURCE_DIR = os.path.abspath(project_dir)


def parse_module_tags(filepath):
    """Read Role:/Domain: out of a module's docstring.

    Returns (role, domain), each either a declared value or
    UNDETERMINED. Uses ast.get_docstring() -- the same call
    get_module_docstring() already makes -- rather than scanning for
    quotes, so a shebang, a comment header, or a quoted string earlier in
    the file cannot be mistaken for the docstring.
    """
    try:
        with open(filepath, 'rb') as handle:
            tree = ast.parse(handle.read())
    except Exception:
        return UNDETERMINED, UNDETERMINED

    doc = ast.get_docstring(tree, clean=False)
    if not doc:
        return UNDETERMINED, UNDETERMINED

    found = dict(TAG_RE.findall(doc))
    role = found.get('Role', UNDETERMINED)
    domain = found.get('Domain', UNDETERMINED)
    if role not in VALID_ROLES:
        role = UNDETERMINED
    return role, domain


def resolve_module_path(module_name):
    """Best guess at where module_name's source lives."""
    if module_name in _MODULE_PATHS:
        return _MODULE_PATHS[module_name]
    return os.path.join(_TAG_SOURCE_DIR, module_name + '.py')


def classify_module(module_name, filepath=None):
    """Classify a module. Returns (role, domain, source).

    Three states, and the source tells you which one you got:

      'tag'          -- the module declares a valid Role. Normal case.
      'legacy'       -- no valid tag, but the regenerated ROLE_MAP mirror
                        still remembers one. Kept for rollout safety; if
                        this fires, a module lost its tag and the atlas
                        says so instead of quietly papering over it.
      'undetermined' -- neither. Reported, never guessed.
    """
    if filepath is None:
        filepath = resolve_module_path(module_name)

    role, domain = parse_module_tags(filepath)
    if role != UNDETERMINED:
        return role, domain, 'tag'

    legacy = ROLE_MAP.get(module_name)
    if legacy in VALID_ROLES:
        return legacy, domain, 'legacy'

    return UNDETERMINED, domain, 'undetermined'


