def regenerate_role_map(modules, source_path=None):
    """Rewrite the ROLE_MAP marker zone in this file from scanned tags.

    ROLE_MAP stopped being the source of truth in L-163 Phase 3 -- the
    docstring tags are. What it still does is give a name-only consumer
    something to fall back on, and give a human a readable roster without
    opening 114 files. So it is regenerated, never hand-edited, using the
    same START/END marker-zone pattern ledger_index.py uses for its INDEX.

    Only modules whose role came from a real tag are written. A module
    that is undetermined is left out rather than frozen into the mirror,
    so a missing tag stays visible instead of curing itself on the next
    run.
    """
    if source_path is None:
        source_path = os.path.abspath(__file__)

    tagged = [m for m in modules if m.get('role_source') == 'tag']
    if not tagged:
        print("  ROLE_MAP: nothing tagged; zone left untouched")
        return False

    width = max(len(m['name']) for m in tagged) + 4
    lines = [ROLE_MAP_START, 'ROLE_MAP = {']
    for role in ROLE_ORDER:
        members = [m for m in tagged if m['role'] == role]
        if not members:
            continue
        lines.append(f'    # {role}')
        for m in sorted(members, key=lambda x: x['name']):
            key = "'" + m['name'] + "':"
            lines.append(f"    {key:<{width}} '{role}',")
        lines.append('')
    if lines[-1] == '':
        lines.pop()
    lines.append('}')
    lines.append(ROLE_MAP_END)
    zone = '\n'.join(lines)

    with open(source_path, 'rb') as handle:
        raw = handle.read()
    ending = b'\r\n' if b'\r\n' in raw else b'\n'
    text = raw.decode('utf-8').replace('\r\n', '\n')

    if (ROLE_MAP_START + '\n') not in text or ('\n' + ROLE_MAP_END) not in text:
        print("  ROLE_MAP: markers not found; zone NOT regenerated")
        return False

    # Anchored at line start on purpose. This file DEFINES the marker
    # strings, so the marker text also appears inside a quoted constant
    # near the top -- an unanchored match would start there and eat the
    # definitions along with the zone.
    pattern = (r'^' + re.escape(ROLE_MAP_START) + r'$.*?^'
               + re.escape(ROLE_MAP_END) + r'$')
    new_text = re.sub(pattern, lambda _m: zone, text,
                      flags=re.DOTALL | re.MULTILINE)
    if new_text == text:
        print(f"  ROLE_MAP: already current ({len(tagged)} modules)")
        return False

    out = new_text.replace('\n', ending.decode('ascii'))
    with open(source_path, 'wb') as handle:
        handle.write(out.encode('utf-8'))
    print(f"  ROLE_MAP: regenerated from tags ({len(tagged)} modules)")
    return True


def classification_report_lines(modules, heading_level='##'):
    """Markdown block naming every module the classifier could not place.

    Exists so an undetermined module is visible in the documents people
    actually read, not just in console output that scrolls past. Silence
    here is the success case: when every module carries a valid tag the
    block says so in one line rather than disappearing, because a section
    that vanishes when clean is indistinguishable from one that broke.
    """
    undetermined = [m for m in modules if m['role'] == UNDETERMINED]
    legacy = [m for m in modules if m.get('role_source') == 'legacy']
    no_domain = [m for m in modules
                 if m.get('domain', UNDETERMINED) == UNDETERMINED]
    # A `patch` module is transient by declaration -- it is not a
    # classification failure, it is a filing step not yet done. It
    # is reported here rather than in the clean roster so that its
    # presence stays visible until it is archived.
    awaiting = [m for m in modules if m['role'] == 'patch']

    out = [f'{heading_level} Classification Coverage', '']
    if not undetermined and not legacy and not no_domain \
            and not awaiting:
        out.append(f'All {len(modules)} modules declare a valid `Role:` and '
                   '`Domain:` tag in their docstring.')
        out.append('')
        return out

    if awaiting:
        out.append(f'**Patch scripts awaiting archive ({len(awaiting)}).** '
                   'A `Role: patch` module is a one-shot script that has '
                   'already run. Its base fingerprint no longer matches, '
                   'so it cannot run again. Move each into '
                   '`documentation/`. While one sits in the scanned tree '
                   'it inflates the module count here and the file count '
                   'in the provenance audit.')
        out.append('')
        for m in awaiting:
            out.append(f'- `{m["path"]}`')
        out.append('')

    if undetermined:
        out.append(f'**Undetermined role ({len(undetermined)}).** No valid '
                   '`Role:` tag in the module docstring. Not guessed -- add '
                   'the tag and re-run `add_docstrings.py`, then this file.')
        out.append('')
        for m in undetermined:
            out.append(f'- `{m["path"]}`')
        out.append('')

    if legacy:
        out.append(f'**Legacy fallback ({len(legacy)}).** No valid tag, but '
                   'the regenerated `ROLE_MAP` mirror still remembered a '
                   'role. These modules lost a tag they used to have.')
        out.append('')
        for m in legacy:
            out.append(f'- `{m["path"]}` -- fell back to `{m["role"]}`')
        out.append('')

    if no_domain:
        out.append(f'**Undetermined domain ({len(no_domain)}).** No valid '
                   '`Domain:` tag.')
        out.append('')
        for m in no_domain:
            out.append(f'- `{m["path"]}`')
        out.append('')

    return out


def generate_atlas(modules, output_path):
    """Write MODULE_ATLAS.md from an already-scanned modules list
    (see scan_modules)."""

    # Group by role
    by_role = {}
    for mod in modules:
        role = mod['role']
        by_role.setdefault(role, []).append(mod)

    # Count totals
    total_lines = sum(m['lines'] for m in modules)
    total_functions = sum(len(m['functions']) for m in modules)

    # Generate markdown
    lines = []
    now = datetime.now().strftime('%B %d, %Y')

    lines.append("# Paloma's Orrery -- Module Atlas")
    lines.append("")
    lines.append(f"Generated: {now}")
    lines.append(f"Modules: {len(modules)} | "
                 f"Functions: {total_functions} | "
                 f"Lines: {total_lines:,}")
    lines.append("")
    lines.extend(classification_report_lines(modules))
    lines.append("---")
    lines.append("")
    lines.append("## How to Use This Document")
    lines.append("")
    lines.append("Upload this file to a Claude session. Then ask questions:")
    lines.append("")
    lines.append('- "What modules are involved in rendering comets?"')
    lines.append('- "I want to add a new spacecraft encounter -- what do I touch?"')
    lines.append('- "What imports spacecraft_encounters and what does it import?"')
    lines.append('- "Show me the pipeline from GUI click to rendered figure"')
    lines.append('- "What would break if I changed constants_new?"')
    lines.append("")
    lines.append("Claude searches this atlas, reads relevant source files,")
    lines.append("and explains in context.")
    lines.append("")
    lines.append("For a lighter, human-browsable version of this same scan, see")
    lines.append("MODULE_INDEX.md (also generated by this script).")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Role summary table
    lines.append("## Roles at a Glance")
    lines.append("")
    lines.append("| Role | Count | Description |")
    lines.append("|------|-------|-------------|")
    for role in ROLE_ORDER:
        if role in by_role:
            desc = ROLE_DESCRIPTIONS.get(role, '')
            count = len(by_role[role])
            lines.append(f"| {role} | {count} | {desc} |")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Module entries grouped by role
    for role in ROLE_ORDER:
        if role not in by_role:
            continue

        role_desc = ROLE_DESCRIPTIONS.get(role, role)
        role_modules = by_role[role]

        lines.append(f"## {role.upper()}: {role_desc}")
        lines.append("")

        for mod in role_modules:
            lines.append(f"### {mod['name']}.py")
            lines.append("")
            lines.append(f"**Role:** {mod['role']} | "
                         f"**Lines:** {mod['lines']:,}")
            lines.append("")

            # Description
            lines.append(f"> {mod['docstring']}")
            lines.append("")

            # Dependencies
            if mod['deps']:
                lines.append(f"**Depends on:** "
                             f"{', '.join(mod['deps'])}")
            else:
                lines.append("**Depends on:** (none)")

            # Consumers
            if mod['consumers']:
                lines.append(f"**Consumed by:** "
                             f"{', '.join(mod['consumers'])}")
            else:
                lines.append("**Consumed by:** (none -- standalone)")

            lines.append("")

            # Public functions
            if mod['functions']:
                lines.append("**Public functions:**")
                lines.append("")
                for sig, doc, lineno in mod['functions']:
                    if doc:
                        lines.append(f"- `{sig}` (line {lineno}) -- {doc}")
                    else:
                        lines.append(f"- `{sig}` (line {lineno})")
                lines.append("")

            lines.append("---")
            lines.append("")

    # Alphabetical quick-reference index at the end
    lines.append("## Alphabetical Index")
    lines.append("")
    lines.append("| Module | Role | Lines | Deps | Consumers |")
    lines.append("|--------|------|------:|-----:|----------:|")
    for mod in sorted(modules, key=lambda m: m['name']):
        lines.append(
            f"| {mod['name']} | {mod['role']} | "
            f"{mod['lines']:,} | {len(mod['deps'])} | "
            f"{len(mod['consumers'])} |"
        )
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("*Generated by module_atlas.py -- "
                 "Paloma's Orrery Developer Tools*")
    lines.append("")

    # Write output
    content = '\n'.join(lines)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(content)

    print(f"Atlas written to {output_path}")
    print(f"  {len(modules)} modules, {total_functions} functions, "
          f"{total_lines:,} lines")

    # Print role summary
    print("\nRole summary:")
    for role in ROLE_ORDER:
        if role in by_role:
            count = len(by_role[role])
            print(f"  {role:20s} {count:3d} modules")

    # Transient class: name the action rather than the count. A
    # zero here is the steady state, so nothing prints when clean.
    awaiting = by_role.get('patch') or []
    if awaiting:
        print(f"\n  {len(awaiting)} patch script(s) awaiting "
              f"archive -- move into documentation/:")
        for mod in awaiting:
            print(f"      {mod['path']}")


