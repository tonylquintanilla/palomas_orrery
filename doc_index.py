#!/usr/bin/env python3
"""doc_index.py -- regenerate README.md's key-documents table from the
documents themselves.

ORRERY repo tool. Run it, or let orrery_maintenance_run.py run it.

    python doc_index.py            regenerate the table in README.md
    python doc_index.py --check    report only; exit 1 on any problem
    python doc_index.py --caps     the document caps (L-522); exit 1 on red

THE CAPS (L-522)
----------------
DOCUMENT_CAPS.md, at the root, holds each working document's cap in
lines and the home its old lines go to (Tony's rulings of 2026-11-10).
--caps reads its table and prints every row: the document, its lines
now, its cap and its home. Red, with the names, when a document is over
its cap, a row's document or its home is not found, a skills/*/SKILL.md
has no row, or a row cannot be read. A cap of "N above the marker"
counts only the lines above the run-record marker (Where We Are's 130);
"none ..." is a row with no cap yet, printed with its size. It writes
nothing. The maintenance run's checker "Document caps" runs it. It
lives here, not in a tool of its own, because this tool already reads
the root's documents and is already in the run.

WHY THIS EXISTS (L-273)
-----------------------
README.md's key-documents table was hand-maintained, and a
hand-maintained list of what is in a directory is a copy that drifts
from the directory. That drift is L-270: the README described a gallery
that no longer existed, and nobody could see it from inside the README.

Tony's proposal, 2026-08-31, and it is the right shape: not a checker
that alarms on the copy, but an INDEXER that regenerates it -- the way
skills_index.py writes the manifest into PROJECT_INSTRUCTIONS.md and
ledger_index.py writes the INDEX into LEDGER_CONSOLIDATED.md. Fix the
producer, not the consumer.

THE DESIGN: EACH DOCUMENT DECLARES ITSELF
-----------------------------------------
The purpose text lives in the document it describes, not in this tool
and not in the README. That is deliberate, and it is copied from
skills_index.py: its editorial column lives in each skill's own
frontmatter, so Tony keeps control of the wording while the target file
stays generated. A dict of descriptions inside this script would be the
shadow store that module_atlas.py already deleted when ROLE_MAP became a
regenerated mirror.

    Markdown:  <!-- Doc-Kind: <kind> | <one-line purpose> -->
    Text:      # Doc-Kind: <kind> | <one-line purpose>

The tag may sit anywhere in the first 40 lines. In markdown it is an
HTML comment, so it is invisible when GitHub renders the page.

THREE KINDS, AND THE DISTINCTION IS THE POINT
---------------------------------------------
    generated       written entirely by a tool. Hand-editing it is an
                    error: the next run destroys the edit.
    zoned           hand-written prose around a marker zone a tool
                    regenerates. Edit the prose, never the zone.
    hand            hand-written throughout.

Nothing in either repository recorded that distinction before, and the
only warning against hand-editing a generated file lived inside the file.

MARKERS MUST ALREADY EXIST
--------------------------
If README.md has no marker zone this reports and exits WITHOUT writing.
That is skills_index.py's behaviour rather than ledger_index.py's
fallback insert, and on purpose: guessing where a table belongs in a
prose document is worse than not writing one.

ONE DOCUMENT CANNOT CARRY THE TAG (L-409)
-----------------------------------------
LICENSE.md must hold the standard MIT text alone, or GitHub does not
recognise the license: on 2026-10-04 its sidebar said "View license",
while the file also held a tag and two sections of attributions (now
NOTICE.md). Its row is described in UNTAGGABLE below, and the report
names it as described there rather than by a tag. It is the only entry;
a second one is a reason to look again, not a pattern to extend.

UNTAGGED DOCUMENTS ARE REPORTED, NEVER DROPPED
----------------------------------------------
A document with no tag still appears in the table, marked untagged, and
is named in the summary. Silence about something unexamined is the
failure mode this project has a gate for; a tidy table that quietly
omits what it could not read would be exactly that.

Role: devtool
Domain: dev_tools

Module created: September 1, 2026 with Anthropic's Claude Opus 5.
Module updated: October 4, 2026 with Anthropic's Claude Opus 5.5 (L-409:
LICENSE.md described here, since it cannot carry the tag).
Module updated: November 10, 2026 with Anthropic's Claude Opus 5.5
(L-522: --caps, the check of DOCUMENT_CAPS.md).
"""

import re
import sys
from pathlib import Path

START = '<!-- DOC-INDEX:START (generated by doc_index.py -- do not edit this zone by hand) -->'
END = '<!-- DOC-INDEX:END -->'

TAG_RE = re.compile(
    r'^\s*(?:<!--|#)\s*Doc-Kind:\s*([a-z-]+)\s*\|\s*(.+?)\s*(?:-->)?\s*$',
    re.MULTILINE)

KIND_LABEL = {
    'generated': 'generated',
    'zoned': 'hand + generated zone',
    'hand': 'hand-written',
}

KIND_ORDER = {'zoned': 0, 'hand': 1, 'generated': 2, '?': 3}

SCAN_SUFFIXES = ('.md', '.txt')

# L-409: documents whose content must stay exact, so they cannot carry a
# tag. Described here instead; see the docstring.
UNTAGGABLE = {
    'LICENSE.md': ('hand', 'The MIT license, as the standard text alone so '
                           'GitHub recognizes it. Attributions are in '
                           'NOTICE.md.'),
}
TAG_SCAN_LINES = 40


def read_tag(path):
    """Return (kind, purpose) or (None, None). Reads the head only."""
    try:
        with open(path, 'r', encoding='utf-8', errors='replace') as fh:
            head = ''.join(fh.readline() for _ in range(TAG_SCAN_LINES))
    except OSError as e:
        return None, 'UNREADABLE: %s' % e
    m = TAG_RE.search(head)
    if not m:
        return None, None
    kind = m.group(1).strip()
    return (kind if kind in KIND_LABEL else '?'), m.group(2).strip()


def collect(root):
    docs = []
    for p in sorted(root.iterdir()):
        if not p.is_file() or p.suffix.lower() not in SCAN_SUFFIXES:
            continue
        kind, purpose = read_tag(p)
        if kind is None and p.name in UNTAGGABLE:
            kind, purpose = UNTAGGABLE[p.name]
        docs.append((p.name, kind, purpose))
    return docs


def render(docs):
    rows = [
        '| Document | Kind | What it is for |',
        '|---|---|---|',
    ]
    for name, kind, purpose in sorted(
            docs, key=lambda d: (KIND_ORDER.get(d[1] or '?', 3), d[0].lower())):
        label = KIND_LABEL.get(kind, '**untagged**')
        text = purpose or '_no Doc-Kind tag; add one to describe it here_'
        rows.append('| [%s](%s) | %s | %s |' % (name, name, label, text))
    return '\n'.join(rows)


# ---- the caps (L-522) --------------------------------------------------

CAPS_PAGE = 'DOCUMENT_CAPS.md'
RUN_RECORD_MARKER = '--- Your run record below this line'
CAPS_ROW_RE = re.compile(
    r'^\|\s*`([^`]+)`\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|\s*$')
CAPS_HEADER_RE = re.compile(r'^\|\s*Document\s*\|')
CAPS_RULE_RE = re.compile(r'^\|[\s:|-]+\|\s*$')
CAP_LINES_RE = re.compile(r'^(\d+)$')
CAP_MARKER_RE = re.compile(r'^(\d+) above the marker$')
CAP_NONE_RE = re.compile(r'^none\b')
HOME_PATH_RE = re.compile(r'^`([^`]+)`$')


def count_lines(text):
    """Lines as an editor numbers them: a last line without its newline
    still counts. Only '\\n' ends a line, so no other character splits one."""
    if not text:
        return 0
    return text.count('\n') + (0 if text.endswith('\n') else 1)


def read_caps_page(root):
    """Return (rows, unreadable). rows: (lineno, doc, cap_text, home_text).
    unreadable: (lineno, line) for each table line no rule could read."""
    text = (root / CAPS_PAGE).read_text(encoding='utf-8', errors='replace')
    rows, unreadable = [], []
    for n, line in enumerate(text.split('\n'), 1):
        if not line.lstrip().startswith('|'):
            continue
        if CAPS_HEADER_RE.match(line) or CAPS_RULE_RE.match(line):
            continue
        m = CAPS_ROW_RE.match(line.strip())
        if m:
            rows.append((n, m.group(1).strip(), m.group(2), m.group(3)))
        else:
            unreadable.append((n, line.strip()))
    return rows, unreadable


def check_caps(root):
    """Print every row of DOCUMENT_CAPS.md -- the document, its lines now,
    its cap and its home -- and exit 1 when a document is over its cap, a
    row's document or home is not found, a SKILL.md has no row, or a row
    cannot be read. Every red names what it is about."""
    page = root / CAPS_PAGE
    if not page.is_file():
        print('DOCUMENT CAPS: RED -- %s not found in %s' % (CAPS_PAGE, root))
        return 1
    rows, unreadable = read_caps_page(root)

    over, missing, no_home, uncapped, seen = [], [], [], [], {}
    printed = []
    for n, doc, cap_text, home_text in rows:
        if doc in seen:
            unreadable.append((n, '%s listed again (first on line %d)'
                               % (doc, seen[doc])))
            continue
        seen[doc] = n
        cap, above_marker = None, False
        m_lines = CAP_LINES_RE.match(cap_text)
        m_marker = CAP_MARKER_RE.match(cap_text)
        if m_lines:
            cap = int(m_lines.group(1))
        elif m_marker:
            cap, above_marker = int(m_marker.group(1)), True
        elif not CAP_NONE_RE.match(cap_text):
            unreadable.append((n, '%s: cap "%s" is not a number of lines, '
                               '"N above the marker" or "none ..."'
                               % (doc, cap_text)))
            continue
        m_home = HOME_PATH_RE.match(home_text)
        if m_home and not (root / m_home.group(1)).is_file():
            no_home.append('%s (home %s)' % (doc, m_home.group(1)))
        path = root / doc
        if not path.is_file():
            missing.append(doc)
            printed.append((doc, 'NOT FOUND', cap_text, home_text))
            continue
        try:
            text = path.read_text(encoding='utf-8', errors='replace')
        except OSError as e:
            unreadable.append((n, '%s: %s' % (doc, e)))
            continue
        if above_marker:
            # The lines above the marker: the marker's own index.
            lines = next((i for i, line in enumerate(text.split('\n'))
                          if line.startswith(RUN_RECORD_MARKER)), None)
            if lines is None:
                unreadable.append((n, '%s: no line beginning "%s"'
                                   % (doc, RUN_RECORD_MARKER)))
                continue
        else:
            lines = count_lines(text)
        if cap is None:
            uncapped.append('%s (%d lines)' % (doc, lines))
        elif lines > cap:
            over.append('%s (%d lines, cap %d)' % (doc, lines, cap))
        printed.append((doc, str(lines), cap_text, home_text))

    skills = sorted(p.relative_to(root).as_posix()
                    for p in (root / 'skills').glob('*/SKILL.md'))
    no_row = [s for s in skills if s not in seen]

    print('Document caps, read from %s: %d row(s)' % (CAPS_PAGE, len(rows)))
    width = max([len(d) for d, _l, _c, _h in printed] + [8])
    print('  %-*s  %9s  %-22s  %s' % (width, 'document', 'lines now',
                                      'cap', 'home'))
    for doc, lines, cap_text, home_text in printed:
        print('  %-*s  %9s  %-22s  %s' % (width, doc, lines, cap_text,
                                          home_text.strip('`')))

    reds = []
    if over:
        reds.append('over its cap: ' + ', '.join(over))
    if missing:
        reds.append('not found: ' + ', '.join(missing))
    if no_home:
        reds.append('home not found: ' + ', '.join(no_home))
    if no_row:
        reds.append('skill with no row: ' + ', '.join(no_row))
    if unreadable:
        reds.append('row cannot be read: ' + '; '.join(
            'line %d, %s' % (n, what) for n, what in unreadable))
    for name in uncapped:
        print('  NO CAP YET: %s; the page says when it gets one.' % name)
    print('')
    if reds:
        print('DOCUMENT CAPS: RED -- ' + ' | '.join(reds))
        return 1
    capped = len(printed) - len(uncapped)
    print('DOCUMENT CAPS: PASS -- %d document(s) within their caps, %d '
          'skill(s) all listed%s'
          % (capped, len(skills),
             ('; no cap yet: ' + ', '.join(uncapped)) if uncapped else ''))
    return 0


def main():
    root = Path(__file__).resolve().parent
    if '--caps' in sys.argv[1:]:
        return check_caps(root)
    check_only = '--check' in sys.argv[1:]
    readme = root / 'README.md'

    if not readme.is_file():
        print('CANNOT RUN: README.md not found in %s' % root)
        return 2

    docs = collect(root)
    untagged = [n for n, k, p in docs if k is None]
    unknown = [(n, p) for n, k, p in docs if k == '?']

    text = readme.read_text(encoding='utf-8')
    if START not in text or END not in text:
        print('CANNOT RUN: README.md has no DOC-INDEX marker zone.')
        print('  Expected these two lines, in this order:')
        print('    %s' % START)
        print('    %s' % END)
        print('  Nothing was written. Guessing an insertion point in a prose')
        print('  document is worse than not writing one.')
        return 2

    table = render(docs)
    new_zone = START + '\n' + table + '\n' + END
    pattern = re.compile(re.escape(START) + r'.*?' + re.escape(END), re.DOTALL)
    updated = pattern.sub(lambda _m: new_zone, text, count=1)

    changed = updated != text
    if changed and not check_only:
        with open(readme, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(updated)

    # ---- report: names, not only counts (A Report Names Its Items) ----
    by_kind = {}
    for name, kind, _p in docs:
        by_kind.setdefault(kind or 'untagged', []).append(name)

    print('%d root document(s) indexed:' % len(docs))
    for kind in ('zoned', 'hand', 'generated', '?', 'untagged'):
        names = by_kind.get(kind)
        if names:
            print('  %-22s %d  %s'
                  % (KIND_LABEL.get(kind, kind), len(names), ', '.join(names)))

    described = [n for n in UNTAGGABLE if (root / n).is_file()]
    if described:
        print('  described in doc_index.py, not by a tag: %s'
              % ', '.join(described))

    problems = 0
    if unknown:
        problems += len(unknown)
        print('')
        print('UNRECOGNISED Doc-Kind value (%d):' % len(unknown))
        for n, _p in unknown:
            print('    %s' % n)
        print('  Valid kinds: %s' % ', '.join(sorted(KIND_LABEL)))

    if untagged:
        print('')
        print('NO Doc-Kind TAG (%d): %s' % (len(untagged), ', '.join(untagged)))
        print('  These appear in the table marked untagged rather than being')
        print('  dropped from it. A document a tool could not read is the')
        print('  thing most worth saying out loud.')

    print('')
    if check_only:
        if changed:
            problems += 1
            print('STALE: README.md\'s table does not match the documents.')
            print('  Run: python doc_index.py')
        else:
            print('OK: README.md\'s table matches the %d root document(s).'
                  % len(docs))
        return 1 if problems else 0

    if changed:
        print('Document index regenerated (%d documents) in README.md.' % len(docs))
    else:
        print('Document index already matched all %d document(s).' % len(docs))
    return 0


if __name__ == '__main__':
    sys.exit(main())
